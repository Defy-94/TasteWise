<?php
/**
 * 核心层自动加载
 *
 * ============================================
 * 【为什么要它】
 *   在它出现之前，全项目有 **93 处手工 require_once**，散落在 28 个文件里。
 *   这带来两个实际成本：
 *     1. 新增一个 core 类，要记得在用到它的每个入口文件里补一行 ——
 *        忘了就是运行时 500，而且报错信息（"Class not found"）指不到根因；
 *     2. core 类之间互相 require，稍微理一下依赖就要动好几个文件。
 *
 *   注册自动加载后：**新增 core 类不需要改任何现有文件**，
 *   用到时按类名自动去找 core/<类名>.php。
 * ============================================
 *
 * ============================================
 * 【设计上的保守之处】
 *   - 只在这个目录（core/）里找，且只接**没有命名空间**的类。
 *     本项目 core/ 下的类都是全局类（DB、Response、Auth…），
 *     这样即使将来引入带命名空间的第三方库，也不会被这里误抓。
 *   - 找不到文件时**什么都不做**（不抛异常），把机会让给其他加载器，
 *     避免自己成为"类找不到"的报错来源。
 * ============================================
 *
 * 用法（放在每个入口文件的 require 区，代替原来的一串 core 依赖）：
 *
 *     require_once __DIR__ . '/../../core/bootstrap.php';
 */

spl_autoload_register(function ($class) {
    // 只处理全局类；带命名空间的（Foo\Bar）交给别的加载器
    if (strpos($class, '\\') !== false) {
        return;
    }

    $file = __DIR__ . DIRECTORY_SEPARATOR . $class . '.php';

    if (is_file($file)) {
        require_once $file;
    }
});
